drop policy if exists "Users can delete own memories" on public.memories;
create policy "Users can delete own memories" on public.memories for delete using (auth.uid() = user_id);

-- Keep updated_at fresh whenever a conversation changes.
create or replace function public.choco_set_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end;
$$;
drop trigger if exists conversations_set_updated_at on public.conversations;
create trigger conversations_set_updated_at before update on public.conversations
for each row execute function public.choco_set_updated_at();

